import { getDb } from '@/db';
import { song as songTable } from '@/db/schema';
import { constructMetadata } from '@/lib/metadata';
import type { Song } from '@/types/song';
import { and, desc, isNotNull, isNull, ne, notInArray, or } from 'drizzle-orm';
import type { Metadata } from 'next';
import { getTranslations } from 'next-intl/server';
import { SongsClientWrapper } from './songs-client-wrapper';

interface SongsPageProps {
  params: Promise<{
    locale: string;
  }>;
}

export async function generateMetadata({ params }: SongsPageProps): Promise<Metadata> {
  const { locale } = await params;
  const t = await getTranslations({ locale, namespace: 'Metadata' });

  return constructMetadata({
    title: `Runway | ScoopRYM Music - ${t('title')}`,
    description: 'Explore the latest AI-generated songs created by the ScoopRYM community.',
    locale,
    pathname: '/songs',
  });
}

export default async function SongsPage({ params }: SongsPageProps) {
  const { locale } = await params;
  const db = await getDb();

  // Fetch latest 50 public songs
  const songs = await db
    .select()
    .from(songTable)
    .where(
      and(
        isNotNull(songTable.audioUrl),
        ne(songTable.audioUrl, 'pending-stream'),
        ne(songTable.audioUrl, ''),
        or(
          isNull(songTable.processingStatus),
          notInArray(songTable.processingStatus, [
            'failed_generation',
            'processing_queue_failed',
            'failed_audio_upload',
            'failed_credit_deduction',
          ])
        )
      )
    )
    .orderBy(desc(songTable.createdAt))
    .limit(50);

  const serializedSongs = songs.map((song) => ({
    ...song,
    createdAt: song.createdAt ? song.createdAt.toISOString() : new Date().toISOString(),
    updatedAt: song.updatedAt ? song.updatedAt.toISOString() : new Date().toISOString(),
  })) as unknown as Song[];

  return (
    <div className="flex flex-col min-h-screen pt-24 pb-20 px-4 md:px-8 max-w-[1800px] mx-auto w-full">
      <div className="text-center space-y-4 mb-16">
        <h1 className="text-5xl md:text-7xl font-black tracking-tighter text-transparent bg-clip-text bg-linear-to-r from-gray-900 via-gray-700 to-gray-900 drop-shadow-sm pb-2 dark:from-white dark:via-gray-200 dark:to-gray-400">
          Community{' '}
          <span className="text-transparent bg-clip-text bg-linear-to-r from-pink-500 to-violet-500">Runway</span>
        </h1>
        <p className="text-xl font-medium text-gray-600 dark:text-gray-400 max-w-2xl mx-auto">
          Discover the latest tracks generated by ScoopRYM AI.
        </p>
      </div>

      <SongsClientWrapper songs={serializedSongs} />
    </div>
  );
}
