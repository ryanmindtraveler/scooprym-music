import { getDb } from '@/db';
import { songFavorite, song as songTable } from '@/db/schema';
import { constructMetadata } from '@/lib/metadata';
import { getSession } from '@/lib/server';
import type { Song } from '@/types/song';
import { and, eq, isNull, notInArray, or } from 'drizzle-orm';
import type { Metadata } from 'next';
import type { Locale } from 'next-intl';
import { notFound } from 'next/navigation';
import { SongDetailClient } from './song-detail-client';

import { BreadcrumbJsonLd, JsonLd } from '@/components/seo/json-ld';
import { getIdFromSlug, slugify } from '@/lib/utils';
import type { MusicRecording, WithContext } from 'schema-dts';

interface SongDetailPageProps {
  params: Promise<{
    slug: string;
    locale: Locale;
  }>;
}

export async function generateMetadata({ params }: SongDetailPageProps): Promise<Metadata> {
  const resolvedParams = await params;
  const { slug, locale } = resolvedParams;
  const id = getIdFromSlug(slug);

  const db = await getDb();

  const [song] = await db
    .select()
    .from(songTable)
    .where(
      and(
        eq(songTable.id, id),
        or(
          isNull(songTable.processingStatus),
          notInArray(songTable.processingStatus, [
            'failed_generation',
            'processing_queue_failed',
            'failed_audio_upload',
            'failed_credit_deduction',
          ])
        )
      )
    )
    .limit(1);

  if (!song) {
    return constructMetadata({
      title: 'Song Not Found',
      locale,
    });
  }

  // Generate strict canonical slug
  const titleSlug = slugify(song.title || 'song');
  const canonicalSlug = `${titleSlug}-${song.id}`;

  // SEO: Enhanced Description using News Summary or Lyrics
  const description =
    song.newsSummary || song.sourceText
      ? `Listen to "${song.title}": ${song.newsSummary || song.sourceText}`.slice(0, 160)
      : `Listen to ${song.title}, an AI comedy rap generated by ScoopRYM.`;

  return constructMetadata({
    title: `${song.title} | ScoopRYM Comedy Rap`,
    description: description,
    image: song.coverImageUrl || undefined,
    locale,
    pathname: `/songs/${canonicalSlug}`, // Enforce strict canonical URL
    keywords: [song.title, 'AI Rap', 'Comedy Music', 'Viral Song', 'Diss Track'],
  });
}

export default async function SongDetailPage({ params }: SongDetailPageProps) {
  const resolvedParams = await params;
  const { slug } = resolvedParams;
  const id = getIdFromSlug(slug);

  const db = await getDb();
  const session = await getSession();
  const userId = session?.user?.id;

  const [song] = await db
    .select()
    .from(songTable)
    .where(
      and(
        eq(songTable.id, id),
        or(
          isNull(songTable.processingStatus),
          notInArray(songTable.processingStatus, [
            'failed_generation',
            'processing_queue_failed',
            'failed_audio_upload',
            'failed_credit_deduction',
          ])
        )
      )
    )
    .limit(1);

  if (!song) {
    notFound();
  }

  // Check favorite status
  let isFavorite = false;
  if (userId) {
    const [fav] = await db
      .select()
      .from(songFavorite)
      .where(and(eq(songFavorite.songId, id), eq(songFavorite.userId, userId)));
    isFavorite = !!fav;
  }

  // Prepare serializable song object
  const serializableSong = {
    ...song,
    createdAt: song.createdAt ? new Date(song.createdAt) : new Date(),
    updatedAt: song.updatedAt ? new Date(song.updatedAt) : new Date(),
    durationSec: song.durationSec || 0,
    plays: song.plays || 0,
  };

  // Generate strict canonical slug
  const titleSlug = slugify(song.title || 'song');
  const canonicalSlug = `${titleSlug}-${song.id}`;

  // Structured Data (Schema.org) for MusicRecording
  const musicRecordingSchema: WithContext<MusicRecording> = {
    '@context': 'https://schema.org',
    '@type': 'MusicRecording',
    name: song.title,
    url: `https://www.scooprym.app/songs/${slugify(song.title || 'song')}-${song.id}`,
    datePublished: song.createdAt ? new Date(song.createdAt).toISOString() : undefined,
    duration: song.durationSec ? `PT${song.durationSec}S` : undefined,
    image: song.coverImageUrl || undefined,
    byArtist: {
      '@type': 'MusicGroup',
      name: 'ScoopRYM Music',
      url: 'https://www.scooprym.app',
    },
    inAlbum: {
      '@type': 'MusicAlbum',
      name: 'ScoopRYM Viral Hits',
    },
  };

  const breadcrumbs = [
    { name: 'Home', item: 'https://www.scooprym.app' },
    { name: 'Songs', item: 'https://www.scooprym.app/songs' },
    { name: song.title, item: `https://www.scooprym.app/songs/${canonicalSlug}` },
  ];

  return (
    // Immersive Full-Page Layout: "Ambient Soft Focus" with Split View
    <div className="min-h-screen w-full bg-slate-50 dark:bg-black">
      <JsonLd data={musicRecordingSchema} />
      <BreadcrumbJsonLd items={breadcrumbs} />

      <SongDetailClient song={serializableSong} initialIsFavorite={isFavorite} autoPlay={true} />
    </div>
  );
}
